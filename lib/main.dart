// ============ CONFIGURATION ============
// Sana'a, Yemen (Amanat Al Asimah). This is an OFFLINE-FIRST build: the transit
// data (GTFS), map tiles (MBTiles) and points of interest are all bundled as
// assets, and the app makes no network calls. The bundled community transport
// data comes from OpenStreetMap (mapped by the Sana'a community).
const _defaultCenter = LatLng(15.3470, 44.2050);
const _appName = "Trufi Sana'a";
const _deepLinkScheme = 'trufiapp';
const _cityName = "Sana'a";
const _countryName = 'Yemen';
const _emailContact = 'info@trufi-association.org';

// UI languages (issue #15). Arabic goes FIRST, not just as the default index:
// core hands `supportedLocales` to MaterialApp, which falls back to the first
// entry when it cannot resolve a locale, and feeds `defaultLocale` to its
// fallback-localizations layer. English stays selectable in the onboarding
// sheet and in settings. Installs that already chose a language keep it:
// LocaleManager restores the saved preference over this default.
const localeConfig = TrufiLocaleConfig(
  supportedLocales: [Locale('ar'), Locale('en')],
  defaultLocaleIndex: 0,
);

// POI GeoJSON assets, also used by the offline address search below. One
// file per category in assets/pois/metadata.json (generated by
// tools/pois-yemen-sanaa); test/offline_poi_search_service_test.dart checks
// the two lists stay in sync.
const poiAssetPaths = <String>[
  'assets/pois/education.geojson',
  'assets/pois/emergency.geojson',
  'assets/pois/finance.geojson',
  'assets/pois/food.geojson',
  'assets/pois/government.geojson',
  'assets/pois/healthcare.geojson',
  'assets/pois/recreation.geojson',
  'assets/pois/religion.geojson',
  'assets/pois/services.geojson',
  'assets/pois/shopping.geojson',
  'assets/pois/tourism.geojson',
  'assets/pois/transport.geojson',
];

// Offline planner configuration (public so `test/planner_reach_test.dart`
// can plan against the bundled feed with exactly these values).
const sanaaPlannerConfig = TrufiPlannerConfig.local(
  gtfsAsset: 'assets/routing/sanaa.gtfs.zip',
  // OTP parity (~20 min access walk; Cochabamba prod uses
  // accessEgress.maxDuration 20m). The 800 m default leaves most of
  // Sana'a's periphery unplannable: 33% of the served area is within
  // 800 m of a stop vs 48% within 1500 m (issue #2). Note the core
  // suppresses transfer options whenever a direct exists, so a far
  // direct boarding can replace short-walk transfer alternatives —
  // deliberate core behavior (one fare per ride) this radius amplifies.
  maxWalkingDistance: 1500,
  // Allow trips with up to four changes of bus (five buses). Sana'a's
  // feed is 194 short lines, so many trips have no direct line and no
  // single change: the reporter's trip in issue #2 (second reopening)
  // needs 7 -> 14 -> 14, and his north-south trip across the city
  // (third reopening, 45 km) needs 7 -> 7 -> 14 -> 14 -> 14 — nothing
  // with three changes exists for it in this feed. Multi-transfer
  // itineraries are only searched when nothing with 0 or 1 transfers
  // exists, and the search stops at the first number of changes that
  // reaches the destination, so trips that already plan do not change
  // (verified: 0 differences on 400 random pairs >= 2 km apart).
  // Plannable pairs in that sample: 54 % with the default (1), 77.5 %
  // with 2 (v1.2.0), 90.3 % with 3, 96.3 % with 4, 99.5 % with 5.
  // Cost of going from 2 to 4 on this feed: +0.45 ms per query on
  // average, 2.6 ms worst case on desktop (roughly 10-15 ms on a
  // phone), paid only by the queries that would otherwise return
  // nothing; ~0.5 MB of transient memory, nothing on disk or at
  // start-up (trufi-core#998 / #999).
  maxTransfers: 4,
  // The planner only boards at the N stops nearest to each endpoint
  // (within maxWalkingDistance). Sana'a's stops are OSM way nodes
  // ~20 m apart (median), so the default pool of 150 reaches only
  // ~1.3 km (median) — it truncated the 1 500 m radius at
  // 59 % of 300 random endpoints and hid lines whose nearest stop is
  // farther than the 150th stop: issue #21 (جامع المرور → the
  // شميلة ⟵ بينون route boards ~1.4 km away, the 150th stop is at
  // 1 188 m). No stop in this feed has more than 520 stops within
  // 1 500 m, so 600 is the first value that never truncates (400 gives
  // the same cards on 300 random pairs, a handful of rows differ). Cost
  // on this feed: 1.2 → 2.0 ms per query on average, ~3 → 7-8 ms worst case
  // on desktop (a few times that on a phone). Not a core default: on
  // Cochabamba's dense feed the same value costs +50 % per query at
  // 800 m and 3x at 1 500 m.
  maxStopCandidates: 600,
  // List the one-change itineraries after the direct lines instead of
  // hiding them (trufi-core#1043, issue #16). The planner computes the
  // one-transfer bucket anyway and, by default, drops it as soon as a
  // direct line exists (one fare per ride); on this feed, where many
  // overlapping lines serve the same corridor, that left 75 % of the
  // plannable trips with a single card. Showing the bucket only adds rows
  // to compare, nothing extra is searched: on 300 random trips >= 2 km,
  // single-card trips 75 % -> 53 % and 1.33 -> 1.87 cards on average
  // (with the pool above), ~2 ms per query on a desktop. Trips with two
  // or more changes still appear only when nothing shorter exists.
  directsHideTransfers: false,
);

// The feed's stops are OSM way nodes placed along each line, not stops
// anyone waits at (issue #18): the route detail keeps the line's name,
// terminals, badge and geometry and drops the stop timeline, the count
// and the dotted markers (trufi-core#1014). Applied to every route detail
// the app opens: the Routes list, a line badge in an itinerary, and the
// nearby-lines rows.
const _routeDetailShowStops = false;

// Routing engines: offline only.
final List<IRoutingProvider> _routingEngines = [
  // Offline routing from the bundled Sana'a GTFS feed (mobile only).
  if (!kIsWeb) TrufiPlannerProvider(config: sanaaPlannerConfig),
];

// Map engines: offline only (Sana'a MBTiles). No online tile servers.
// No `displayName`/`displayDescription` on purpose: without them the engine
// shows core's localized `offlineMapName`/`offlineMapDescription` (Arabic
// from tools/l10n/i18n/ar/maps.arb), so the map card of the onboarding and
// the map settings sheet follow the UI language instead of a hardcoded
// English label (issue #15). Public for test/maps_l10n_test.dart.
final List<ITrufiMapEngine> mapEngines = [
  if (!kIsWeb)
    OfflineMapLibreEngine(
      engineId: 'offline_osm_liberty',
      config: OfflineMapConfig(
        mbtilesAsset: 'assets/offline/sanaa.mbtiles',
        styleAsset: 'assets/offline/styles/osm-liberty/style.json',
        spritesAssetDir: 'assets/offline/styles/osm-liberty/',
        fontsAssetDir: 'assets/offline/fonts/',
        fontMapping: {
          'RobotoRegular': 'Roboto Regular',
          'RobotoMedium': 'Roboto Medium',
          'RobotoCondensedItalic': 'Roboto Condensed Italic',
        },
        fontRanges: [
          '0-255',
          '256-511',
          '512-767',
          '768-1023',
          '1024-1279',
          '1280-1535',
          // Arabic block + Arabic Supplement. Without these, no Arabic map
          // label can render at all ("Failed to load glyph range 1536-1791")
          // — and Sana'a is labeled in Arabic everywhere. Glyphs come from
          // Klokantech Noto Sans (Roboto has no Arabic coverage).
          '1536-1791',
          '1792-2047',
          '8192-8447',
          '8448-8703',
          // Arabic Presentation Forms A/B: MapLibre's text shaping requests
          // these for joined (cursive) letterforms.
          '64256-64511',
          '64512-64767',
          '64768-65023',
          '65024-65279',
        ],
      ),
    ),
];
// ========================================

void main() {
  runTrufiApp(
    AppConfiguration(
      appName: _appName,
      deepLinkScheme: _deepLinkScheme,
      // Arabic (RTL) UI by default, English available in the onboarding
      // language picker and in settings — see `localeConfig` above.
      // Arabic for all screens is provided APP-SIDE via extraLocalizationsDelegates
      // (see lib/l10n/), so this app uses the official trufi-core — no fork.
      localeConfig: localeConfig,
      // Pin routing to midday so the offline planner returns results regardless
      // of when the app is opened; the time picker stays hidden.
      routingTimeOverride: const TimeOfDay(hour: 12, minute: 0),
      extraLocalizationsDelegates: [
        // Arabic for all trufi-core screens — provided app-side (lib/l10n/),
        // so this app uses official trufi-core (no fork) for the language.
        ...L10n.delegates,
      ],
      themeConfig: TrufiThemeConfig(
        theme: ThemeData(
          colorScheme: ColorScheme.fromSeed(seedColor: const Color(0xFF1E88E5)),
          useMaterial3: true,
        ),
        darkTheme: ThemeData(
          colorScheme: ColorScheme.fromSeed(
            seedColor: const Color(0xFF1E88E5),
            brightness: Brightness.dark,
          ),
          useMaterial3: true,
        ),
      ),
      providers: [
        ChangeNotifierProvider(
          create: (_) => MapEngineManager(
            engines: mapEngines,
            defaultCenter: _defaultCenter,
            // Open zoomed into central Sana'a so the street grid is visible.
            defaultZoom: 14,
          ),
        ),
        ChangeNotifierProvider(
          create: (_) => RoutingEngineManager(engines: _routingEngines),
        ),
        ChangeNotifierProvider(
          create: (_) => OverlayManager(
            managers: [
              OnboardingManager(
                overlayBuilder: (onComplete) =>
                    OnboardingSheet(onComplete: onComplete),
              ),
              // No privacy-consent overlay: this is an offline-first build that
              // collects and transmits nothing, so a data-collection consent
              // prompt would be misleading.
            ],
          ),
        ),
        BlocProvider(
          create: (_) => SearchLocationsCubit(
            // Offline-first: search the bundled Sana'a POIs, no network.
            searchLocationService: OfflinePoiSearchService(
              poiAssetPaths: poiAssetPaths,
              biasLatitude: _defaultCenter.latitude,
              biasLongitude: _defaultCenter.longitude,
            ),
          ),
        ),
      ],
      screens: [
        HomeScreenTrufiScreen(
          config: HomeScreenConfig(
            appName: _appName,
            deepLinkScheme: _deepLinkScheme,
            poiLayersManager: POILayersManager(assetsBasePath: 'assets/pois'),
          ),
          onStartNavigation: (context, itinerary, locationService) {
            NavigationScreen.showFromItinerary(
              context,
              itinerary: itinerary,
              locationService: locationService,
              mapEngineManager: MapEngineManager.read(context),
            );
          },
          onRouteTap: (context, routeCode) {
            TransportDetailScreen.show(context, routeCode: routeCode);
          },
          // "Lines along <street>", first row of a street's corners list in
          // the search (trufi-core#1051, issue #20): opens the nearby-lines
          // screen over every corner of the street at once, each line listed
          // once at its nearest corner. Core shows the row only when the app
          // wires this handler; the row label and the screen header come
          // localized from core (Arabic from lib/l10n/).
          onLinesAlongStreet: (context, street, corners) {
            NearbyLinesTrufiScreen.showAlongStreet(
              context,
              NearbyStreetAnchor(
                name: street.displayName,
                subtitle: street.address,
                corners: [
                  for (final corner in corners)
                    LatLng(corner.latitude, corner.longitude),
                ],
              ),
            );
          },
        ),
        SavedPlacesTrufiScreen(),
        // Bookmarked origin-destination trips, "Your Routes"
        // (trufi-core#1008). Registering it also puts the bookmark button on
        // the route results; endpoints are stored as coordinates and names,
        // so saved routes survive a feed refresh.
        SavedRoutesTrufiScreen(),
        TransportListTrufiScreen(showStops: _routeDetailShowStops),
        // Lines passing within 100 / 300 / 500 m of the rider or of a pin
        // long-pressed on its map, computed on the device from the bundled
        // GTFS of the offline planner (trufi-core#1009, issue #20).
        NearbyLinesTrufiScreen(showStops: _routeDetailShowStops),
        SettingsTrufiScreen(),
        AboutTrufiScreen(
          config: AboutScreenConfig(
            appName: _appName,
            cityName: _cityName,
            countryName: _countryName,
            emailContact: _emailContact,
          ),
        ),
      ],
    ),
  );
}
